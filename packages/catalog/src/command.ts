import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createTheme, themeToCss } from "@ux-sting/themes";
import { brief, camel, renderBrief } from "./brief.js";
import { DOMAINS, stats, type Domain } from "./data.js";
import { search, titleOf } from "./search.js";

type Print = (line: string) => void;

const option = (argv: string[], name: string) => {
  const i = argv.indexOf(`--${name}`);
  if (i >= 0 && argv[i + 1] && !argv[i + 1]!.startsWith("--")) return argv[i + 1];
  const inline = argv.find((a) => a.startsWith(`--${name}=`));
  return inline?.slice(name.length + 3);
};
const positional = (argv: string[], valued: string[]) =>
  argv.filter((a, i) => !a.startsWith("--") && !valued.includes(argv[i - 1] ?? ""));

export const BRIEF_HELP = `ux-sting brief "<product or idea>" — industry-aware design system + a real UX-STING theme

  --out <dir>      Write <name>.theme.ts/.json/.css and design-system.md here
  --name <name>    Theme name (default: the product type)
  --style <name>   Force a style (e.g. "neubrutalism", "glassmorphism")
  --stack <name>   Add stack guidelines (react, nextjs, vue, svelte, astro, flutter, swiftui, …)
  --json           Print JSON

Examples
  npx ux-sting brief "beauty spa booking"
  npx ux-sting brief "crypto exchange dashboard" --stack nextjs --out src/theme`;

export async function briefCommand(argv: string[], print: Print = console.log): Promise<number> {
  const query = positional(argv, ["--out", "--name", "--style", "--stack"]).join(" ").trim();
  if (!query || argv.includes("--help")) {
    print(BRIEF_HELP);
    return query ? 0 : 1;
  }
  const result = brief(query, {
    name: option(argv, "name"),
    style: option(argv, "style"),
    stack: option(argv, "stack"),
  });
  const md = renderBrief(result);
  if (argv.includes("--json")) print(JSON.stringify(result, null, 2));
  else print(md);

  const outDir = option(argv, "out");
  if (outDir && result.theme) {
    const out = resolve(outDir);
    mkdirSync(out, { recursive: true });
    const { config } = result.theme;
    const json = JSON.stringify(config, null, 2);
    const id = camel(config.name);
    writeFileSync(join(out, `${config.name}.theme.json`), json + "\n");
    writeFileSync(
      join(out, `${config.name}.theme.ts`),
      `import { createTheme, type ThemeConfig } from "@ux-sting/themes";\n\n// Generated by \`ux-sting brief "${query.replace(/[`"\\]/g, "")}"\`.\nexport const ${id}Config = ${json} satisfies ThemeConfig;\n\nexport const ${id} = createTheme(${id}Config);\n`,
    );
    writeFileSync(join(out, `${config.name}.css`), themeToCss(createTheme(config)) + "\n");
    writeFileSync(join(out, "design-system.md"), md);
    print(`Wrote ${join(out, `${config.name}.theme.ts`)}, .theme.json, .css and design-system.md`);
  }
  return 0;
}

export const SEARCH_HELP = `ux-sting search <domain> "<query>" — search the design knowledge base

Domains: ${DOMAINS.join(", ")}

  --limit <n>      Results (default 5)
  --stack <name>   With "stacks": one stack only (react, vue, flutter, …)
  --json           Print JSON

Examples
  npx ux-sting search styles "glass dark premium"
  npx ux-sting search typography "playful kids"
  npx ux-sting search charts "funnel conversion"
  npx ux-sting search stacks "image loading" --stack nextjs`;

export async function searchCommand(argv: string[], print: Print = console.log): Promise<number> {
  const [domain, ...words] = positional(argv, ["--limit", "--stack"]);
  if (argv.includes("--stats")) {
    print(JSON.stringify(stats(), null, 2));
    return 0;
  }
  if (!domain || !words.length || argv.includes("--help") || !DOMAINS.includes(domain as Domain)) {
    print(SEARCH_HELP);
    if (domain && !DOMAINS.includes(domain as Domain)) print(`\nUnknown domain "${domain}".`);
    return argv.includes("--help") ? 0 : 1;
  }
  const d = domain as Domain;
  const hits = search(d, words.join(" "), {
    limit: Number(option(argv, "limit") ?? 5) || 5,
    stack: option(argv, "stack"),
  });
  if (argv.includes("--json")) {
    print(JSON.stringify(hits, null, 2));
    return 0;
  }
  if (!hits.length) {
    print(`No ${d} match "${words.join(" ")}".`);
    return 0;
  }
  for (const { record, score } of hits) {
    print(`## ${titleOf(d, record)}  ${"·"} ${score.toFixed(2)}`);
    for (const [k, v] of Object.entries(record))
      if (v && k !== Object.keys(record)[0] && String(v).length < 400) print(`- ${k}: ${v}`);
    print("");
  }
  return 0;
}
