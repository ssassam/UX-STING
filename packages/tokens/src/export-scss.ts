import { derivedVars, staticVars, type CssVars } from "./css.js";
import { createDarkColors, createHighContrastColors, createLightColors } from "./semantic.js";

/**
 * SCSS ($variable) export of the token set, for Sass-based pipelines outside
 * the React system (Vue, Angular, plain CSS tooling that compiles Sass). The
 * names mirror the CSS custom properties (`--ui-primary` becomes `$ui-primary`)
 * so a project can consume both from one source of truth.
 */

/** `--ui-foo` -> `$ui-foo`; a bare role `primary` -> `$ui-primary`. */
const scssName = (name: string) => `$${name.startsWith("--") ? name.slice(2) : `ui-${name}`}`;

const toPairs = (vars: CssVars): string[] =>
  Object.entries(vars).map(([name, value]) => `${scssName(name)}: ${value};`);

/** Emits the resolved base (light) tokens as SCSS variables. */
export function generateScss(): string {
  const light = createLightColors();
  const dark = createDarkColors();
  const hc = createHighContrastColors();

  const lightColorPairs = Object.entries(light).map(([role, value]) => `$ui-${role}: ${value};`);

  return [
    "/* ux-sting design tokens (SCSS) — generated by `ux-sting tokens export`, do not edit. */",
    "/* Light / base mode. Dark and high-contrast values are available via DTCG or tokens.css. */",
    "/* Names mirror the CSS custom properties: --ui-primary -> $ui-primary. */",
    "",
    "/* --- Static scales --- */",
    ...toPairs(staticVars()),
    "",
    "/* --- Derived radius (references $ui-radius) --- */",
    ...Object.entries(derivedVars()).map(([name, value]) => {
      const scssValue = value.replace(/var\(--ui-([a-z0-9-]+)\)/g, "$ui-$1");
      return `${scssName(name)}: ${scssValue};`;
    }),
    "",
    "/* --- Semantic colors (light) --- */",
    ...lightColorPairs,
    "",
    "/* --- Semantic colors (dark) map --- */",
    `$ui-dark: (${Object.entries(dark)
      .map(([k, v]) => `"${k}": ${v}`)
      .join(", ")});`,
    "",
    "/* --- Semantic colors (high-contrast) map --- */",
    `$ui-high-contrast: (${Object.entries(hc)
      .map(([k, v]) => `"${k}": ${v}`)
      .join(", ")});`,
    "",
  ].join("\n");
}
