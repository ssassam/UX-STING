import type { ImageResult, LicenseCode } from "./sources.js";

const LABEL: Record<LicenseCode, string> = {
  cc0: "CC0",
  pdm: "Public domain",
  by: "CC BY",
  "by-sa": "CC BY-SA",
};

const SOURCE: Record<ImageResult["source"], string> = {
  openverse: "Openverse",
  commons: "Wikimedia Commons",
  met: "The Metropolitan Museum of Art",
};

export const licenseLabel = (r: Pick<ImageResult, "license" | "licenseVersion">) =>
  r.licenseVersion && (r.license === "by" || r.license === "by-sa")
    ? `${LABEL[r.license]} ${r.licenseVersion}`
    : LABEL[r.license];

/** True when the license requires credit (BY, BY-SA). PD/CC0 are credited anyway, as a courtesy. */
export const attributionRequired = (r: Pick<ImageResult, "license">) =>
  r.license === "by" || r.license === "by-sa";

/** Plain-text credit in TASL order: Title, Author, Source, License. */
export function creditText(r: ImageResult): string {
  const by = r.creator ? ` by ${r.creator}` : "";
  return `“${r.title}”${by}, ${licenseLabel(r)}, via ${SOURCE[r.source]}`;
}

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** HTML credit with links to the source page and the license deed. */
export function creditHtml(r: ImageResult): string {
  const title = `<a href="${esc(r.landingUrl)}">“${esc(r.title)}”</a>`;
  const by = r.creator ? ` by ${esc(r.creator)}` : "";
  const lic = r.licenseUrl
    ? `<a href="${esc(r.licenseUrl)}" rel="license">${esc(licenseLabel(r))}</a>`
    : esc(licenseLabel(r));
  return `${title}${by}, ${lic}, via ${esc(SOURCE[r.source])}`;
}

/** A local image recorded in the project's credits manifest. */
export interface CreditEntry extends ImageResult {
  /** Path of the downloaded file, relative to the manifest. */
  file: string;
  credit: string;
  creditHtml: string;
  attributionRequired: boolean;
  /** Short alt text draft from the title — rewrite it for the page's context. */
  altDraft: string;
}

export function toEntry(r: ImageResult, file: string): CreditEntry {
  return {
    ...r,
    file,
    credit: creditText(r),
    creditHtml: creditHtml(r),
    attributionRequired: attributionRequired(r),
    altDraft: r.title
      .replace(/\s*\(.*?\)\s*/g, " ")
      .replace(/\s+/g, " ")
      .trim(),
  };
}

/** CREDITS.md for the project, grouped by license. */
export function creditsMarkdown(entries: CreditEntry[]): string {
  const lines = [
    "# Image credits",
    "",
    "Generated by `ux-sting images`. Keep this file and show each credit near its image or on a credits page.",
    "",
    "| File | Credit | License |",
    "| --- | --- | --- |",
  ];
  for (const e of [...entries].sort((a, b) => a.file.localeCompare(b.file)))
    lines.push(
      `| \`${e.file}\` | [“${e.title.replace(/\|/g, "\\|")}”](${e.landingUrl})${e.creator ? ` by ${e.creator.replace(/\|/g, "\\|")}` : ""} | ${e.licenseUrl ? `[${licenseLabel(e)}](${e.licenseUrl})` : licenseLabel(e)} |`,
    );
  if (entries.some((e) => e.license === "by-sa"))
    lines.push(
      "",
      "CC BY-SA: if you adapt an image (crop, retouch, composite), say it was modified and release the adapted image under CC BY-SA. Showing it unmodified beside your own content does not change your site's license.",
    );
  return lines.join("\n") + "\n";
}
