#!/usr/bin/env node
/**
 * Generates a Storybook story file for every component that has no
 * hand-written `*.stories.tsx`, re-exporting its docs demos
 * (apps/docs/demos/<name>.tsx) as stories. Output: apps/storybook/stories/.
 * Run after adding a component or demo: `pnpm stories`.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const componentsDir = join(root, "packages/react/src/components");
const demosDir = join(root, "apps/docs/demos");
const outDir = join(root, "apps/storybook/stories");

const registry = readFileSync(join(root, "registry/components.ts"), "utf8");
const meta = new Map();
for (const m of registry.matchAll(
  /name: "([a-z0-9-]+)",\s*title: "([^"]+)",\s*category: "([a-z-]+)"/g,
)) {
  meta.set(m[1], { title: m[2], category: m[3] });
}
const CLOCK_DEPENDENT =
  /<(?:OpeningHours|OpenStatus|Calendar|DatePicker|DateRangePicker|DateTimePicker)\b|new Date\(\)|Date\.now\(/;
const categoryTitle = (slug) => slug.charAt(0).toUpperCase() + slug.slice(1).replace(/-/g, " ");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

let count = 0;
for (const name of readdirSync(componentsDir).sort()) {
  const dir = join(componentsDir, name);
  if (readdirSync(dir).some((f) => f.endsWith(".stories.tsx"))) continue;
  const demo = join(demosDir, `${name}.tsx`);
  if (!existsSync(demo)) continue;
  const exports = [...readFileSync(demo, "utf8").matchAll(/^export function ([A-Z]\w*)/gm)].map(
    (m) => m[1],
  );
  if (!exports.length) continue;
  const info = meta.get(name) ?? { title: name, category: "other" };
  // Demos that read the current date get a pinned clock in visual tests.
  const clock = CLOCK_DEPENDENT.test(readFileSync(demo, "utf8"));
  const lines = [
    "// Generated by scripts/generate-demo-stories.mjs from apps/docs/demos. Do not edit.",
    'import type { Meta, StoryObj } from "@storybook/react-vite";',
    `import { ${exports.join(", ")} } from "../../docs/demos/${name}.js";`,
    "",
    `const meta = { title: "${categoryTitle(info.category)}/${info.title}"${clock ? ', tags: ["fixed-clock"]' : ""} } satisfies Meta;`,
    "export default meta;",
    "",
    ...exports.map(
      (e) =>
        `export const ${e}Story: StoryObj = { name: "${e.replace(/([a-z])([A-Z])/g, "$1 $2")}", render: () => <${e} /> };`,
    ),
    "",
  ];
  writeFileSync(join(outDir, `${name}.stories.tsx`), lines.join("\n"));
  count++;
}
console.log(`Generated ${count} demo story files → apps/storybook/stories`);
